#!/usr/bin/env node
/* global process, console */
/**
 * 生成一个本地示例 PDF（纯文本 + 简单矢量图形，不依赖外部字体/cmap），
 * 用于离线演示文本选择、查找、缩放、打印等能力。
 *
 * 用法：node scripts/make-sample-pdf.mjs [输出路径]
 */
import { mkdirSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const outPath = process.argv[2]
  ? resolve(process.argv[2])
  : resolve(dirname(fileURLToPath(import.meta.url)), "../public/sample.pdf")

const PAGE_W = 612
const PAGE_H = 792

const SECTIONS = [
  {
    title: "PdfPreview Plugin Demo",
    body: [
      "This is a local sample PDF generated by a script, used to verify",
      "the plugin: text selection, search highlight, zoom, rotation,",
      "thumbnails, print and download.",
    ],
  },
  {
    title: "What is PDF.js?",
    body: [
      "PDF.js is a Portable Document Format (PDF) viewer that is built",
      "with HTML5. It is used by Firefox and many other products.",
    ],
  },
  {
    title: "Large file support",
    body: [
      "The viewer renders pages lazily: only pages near the viewport",
      "are rasterized, and out-of-view rendering is cancelled on scroll.",
      "Range requests stream the document in 64KB chunks when the",
      "server supports byte ranges.",
    ],
  },
  {
    title: "Text layer",
    body: [
      "Every page renders an invisible text layer on top of the canvas,",
      "so you can select, copy and search the text like in a native",
      "browser PDF viewer.",
    ],
  },
  {
    title: "Search & highlight",
    body: [
      "Press Ctrl+F (or Cmd+F) to open the find bar. Matches are",
      "highlighted across all pages, with match count and case",
      "sensitive options.",
    ],
  },
  {
    title: "Shortcuts",
    body: [
      "f: find   t: thumbnails   d: download   p: print",
      "Ctrl+0: actual size   Ctrl++ / Ctrl+-: zoom   R: rotate",
    ],
  },
]

/** 通过 PAGES 环境变量可生成多页大文件（重复内容），用于大文件测试。 */
const pageCount = Number(process.env.PAGES) || SECTIONS.length
const sections = Array.from({ length: pageCount }, (_, i) => SECTIONS[i % SECTIONS.length])

function esc(text) {
  return text.replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)")
}

function contentStream(section, pageNo) {
  const lines = []
  // 顶部标题栏
  lines.push("0.15 0.35 0.65 rg")
  lines.push(`0 ${PAGE_H - 90} ${PAGE_W} 90 re f`)
  lines.push("1 1 1 rg")
  lines.push("BT /F1 26 Tf 48 730 Td (" + esc(section.title) + ") Tj ET")
  // 正文
  lines.push("0 0 0 rg")
  lines.push("BT /F1 12 Tf 48 660 Td 14 TL")
  for (const line of section.body) {
    lines.push("(" + esc(line) + ") Tj T*")
  }
  lines.push("ET")
  // 底部装饰条 + 页码
  lines.push("0.85 0.45 0.2 rg")
  lines.push(`0 0 ${PAGE_W} 26 re f`)
  lines.push("1 1 1 rg")
  lines.push(`BT /F1 10 Tf 48 9 Td (Page ${pageNo}) Tj ET`)
  return lines.join("\n")
}

const n = sections.length
const fontObj = 1
const contentObj = (i) => 2 + 2 * i
const pageObj = (i) => 3 + 2 * i
const pagesObj = 2 + 2 * n
const catalogObj = 3 + 2 * n

let out = "%PDF-1.4\n"
const offsets = []

function addObject(body) {
  offsets.push(out.length)
  out += `${offsets.length} 0 obj\n${body}\nendobj\n`
}

addObject("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>")

for (let i = 0; i < n; i++) {
  const stream = contentStream(sections[i], i + 1)
  addObject(`<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`)
  addObject(
    `<< /Type /Page /Parent ${pagesObj} 0 R /MediaBox [0 0 ${PAGE_W} ${PAGE_H}] ` +
      `/Resources << /Font << /F1 ${fontObj} 0 R >> >> /Contents ${contentObj(i)} 0 R >>`,
  )
}

addObject(
  `<< /Type /Pages /Kids [${Array.from({ length: n }, (_, i) => `${pageObj(i)} 0 R`).join(" ")}] /Count ${n} >>`,
)
addObject(`<< /Type /Catalog /Pages ${pagesObj} 0 R >>`)

const xrefStart = out.length
out += `xref\n0 ${offsets.length + 1}\n`
out += "0000000000 65535 f \n"
for (const offset of offsets) {
  out += `${String(offset).padStart(10, "0")} 00000 n \n`
}
out += `trailer\n<< /Size ${offsets.length + 1} /Root ${catalogObj} 0 R >>\n`
out += "startxref\n" + xrefStart + "\n%%EOF\n"

mkdirSync(dirname(outPath), { recursive: true })
writeFileSync(outPath, out)
console.log(`已生成 ${outPath}（${n} 页，${out.length} 字节）`)
